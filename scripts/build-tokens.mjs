// Generates the brand block of src/styles/tokens.css and convex/email/templates/emailTheme.ts
// from docs/brand/08-handoff/worldling.tokens.json (ADR-018). `--check` fails on drift instead.
import { readFile, writeFile } from "node:fs/promises";

import { format, resolveConfig } from "prettier";

const root = new URL("../", import.meta.url);
const source = "docs/brand/08-handoff/worldling.tokens.json";
const cssPath = "src/styles/tokens.css";
const emailPath = "convex/email/templates/emailTheme.ts";
const start = "/* @generated brand:start (scripts/build-tokens.mjs, do not edit by hand) */";
const end = "/* @generated brand:end */";

const t = JSON.parse(await readFile(new URL(source, root), "utf8"));
const lowerHex = (value) => String(value).replace(/#[0-9A-F]{3,8}\b/gi, (hex) => hex.toLowerCase());

function themeVariables() {
  const vars = [];
  const add = (name, value) => vars.push([name, lowerHex(value)]);
  const flatten = (prefix, object) => {
    for (const [key, value] of Object.entries(object)) {
      if (value && typeof value === "object") flatten(`${prefix}-${key}`, value);
      else add(`${prefix}-${key}`, value);
    }
  };
  flatten("--color", t.color);
  flatten("--font", t.typography.family);
  flatten("--font-weight", t.typography.weight);
  for (const [name, s] of Object.entries(typeStyles())) {
    add(`--text-${name}`, s.size);
    add(`--text-${name}--line-height`, s.lineHeight);
    add(`--text-${name}--letter-spacing`, s.letterSpacing);
    add(`--text-${name}--font-weight`, s.weight);
  }
  flatten("--radius", t.radius);
  add("--spacing", t.spacing.unit);
  flatten("--spacing", t.spacing.scale);
  flatten("--shadow", t.shadow);
  flatten("--duration", t.motion.duration);
  flatten("--ease", t.motion.ease);
  for (const group of ["blur", "border", "size", "layout", "gradient", "icon"]) {
    flatten(`--${group}`, t[group]);
  }
  add("--measure-body", t.typography.bodyMeasure);
  add("--measure-display", t.typography.displayMeasure);
  add("--display-width", t.typography.displayWidth);
  if (new Set(vars.map(([name]) => name)).size !== vars.length) {
    throw new Error("Duplicate CSS variable");
  }
  return vars;
}

function typeStyles() {
  return { ...t.typography.scale, ...t.typography.ui };
}

function brandCss() {
  let css = `${start}\n@theme static {\n`;
  css += themeVariables()
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");
  css += "\n}\n";
  for (const name of Object.keys(t.motion.duration)) {
    css += `\n@utility duration-${name} {\n  transition-duration: var(--duration-${name});\n}\n`;
  }
  for (const [name, s] of Object.entries(typeStyles())) {
    css += `\n@utility wl-${name} {\n  font-family: var(--font-${s.family});\n`;
    css += `  font-size: var(--text-${name});\n  font-weight: var(--text-${name}--font-weight);\n`;
    css += `  line-height: var(--text-${name}--line-height);\n`;
    css += `  letter-spacing: var(--text-${name}--letter-spacing);\n`;
    if (s.family === "display")
      css += "  font-optical-sizing: auto;\n  font-stretch: var(--display-width);\n";
    if (s.family === "mono") css += "  font-variant-numeric: tabular-nums;\n";
    css += "}\n";
  }
  css += "\n@utility bg-worldling-gradient {\n  background-image: var(--gradient-worldling);\n}\n";
  return `${css}${end}`;
}

function remToPx(value) {
  const match = /^(\d*\.?\d+)(rem|px)$/.exec(value);
  if (!match) throw new Error(`Not a rem or px value: ${value}`);
  return match[2] === "rem" ? Number(match[1]) * t.meta.referenceRootPx : Number(match[1]);
}

function emailTheme() {
  const colors = Object.entries(t.color).filter(
    ([, value]) => typeof value === "string" && /^#[0-9a-f]{6}$/i.test(value),
  );
  const radius = Object.entries(t.radius).map(([name, value]) => [name, remToPx(value)]);
  return [
    `// Generated by scripts/build-tokens.mjs from ${source}. Do not edit by hand.`,
    "// Email clients need literal values, so these mirror src/styles/tokens.css (same source).",
    `export const emailColors = ${JSON.stringify(Object.fromEntries(colors.map(([k, v]) => [k, v.toLowerCase()])))} as const;`,
    `export const emailFonts = ${JSON.stringify(t.typography.family)} as const;`,
    `export const emailWeights = ${JSON.stringify(t.typography.weight)} as const;`,
    `export const emailRadius = ${JSON.stringify(Object.fromEntries(radius))} as const;`,
    "",
  ].join("\n");
}

async function pretty(text, path) {
  const options = await resolveConfig(new URL(path, root));
  return format(text, { ...options, filepath: path });
}

async function buildCss() {
  const current = await readFile(new URL(cssPath, root), "utf8");
  const from = current.indexOf(start);
  const to = current.indexOf(end);
  if (from === -1 || to === -1) throw new Error(`Missing generated markers in ${cssPath}`);
  return pretty(current.slice(0, from) + brandCss() + current.slice(to + end.length), cssPath);
}

const outputs = [
  [cssPath, await buildCss()],
  [emailPath, await pretty(emailTheme(), emailPath)],
];

if (process.argv.includes("--check")) {
  const stale = [];
  for (const [path, text] of outputs) {
    const current = await readFile(new URL(path, root), "utf8").catch(() => "");
    if (current !== text) stale.push(path);
  }
  if (stale.length > 0) {
    console.error(`Out of date with ${source}: ${stale.join(", ")}. Run pnpm tokens.`);
    process.exit(1);
  }
  console.log("Brand tokens are up to date.");
} else {
  for (const [path, text] of outputs) await writeFile(new URL(path, root), text);
  console.log(`Wrote ${outputs.map(([path]) => path).join(", ")}`);
}
